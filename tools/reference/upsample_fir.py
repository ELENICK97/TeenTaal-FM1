#!/usr/bin/env python3
"""Step 2b: the half-band filter that brings the tanpura from the strings' rate (22058.8 Hz) to the FM-1's
(44117.6 Hz). Pass band to 9.5 kHz, stop band from 12.56 kHz (symmetric about fs/4, as a half-band filter is).
Only the odd-offset taps are non-zero besides the centre (0.5), and they are symmetric: per input sample one output
is the input itself (delayed) and the other K multiply-adds of pairs.
    ~/.venvs/teentaal/bin/python tools/reference/upsample_fir.py [NTAPS]   -> tanpura/upsample_coefs.h"""
import os, sys
import numpy as np
from scipy import signal

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
FS = 24e6 / 544

def design(ntaps):
    h = signal.remez(ntaps, [0, 9500, FS / 2 - 9500, FS / 2], [1, 0], fs=FS)
    c = (ntaps - 1) // 2
    h[c] = 0.5                                       # exact half-band
    for k in range(2, c + 1, 2):
        h[c - k] = h[c + k] = 0.0
    f, H = signal.freqz(2 * h, worN=8192, fs=FS)
    stop = 20 * np.log10(np.max(np.abs(H[f > FS / 2 - 9500])) + 1e-12)
    ripple = 20 * np.log10(np.max(np.abs(H[f < 9500]))) - 20 * np.log10(np.min(np.abs(H[f < 9500])))
    return h, stop, ripple

def main():
    for n in (23, 31, 39, 47, 55):
        h, st, rp = design(n)
        print(f"{n} taps ({(n + 1) // 4} pair-MACs per input sample): images below {st:.1f} dB, pass-band ripple {rp:.3f} dB")
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 39
    h, st, rp = design(n)
    c = (n - 1) // 2
    odd = h[c + 1::2] * 2                            # the taps at offsets 1, 3, 5, ... (x2: the zero-stuffing gain)
    with open(os.path.join(ROOT, "tanpura", "upsample_coefs.h"), "w") as f:
        f.write("/* upsample_coefs.h — GENERATED by tools/reference/upsample_fir.py: do not edit.\n"
                f" * Half-band interpolator x2, {n} taps: images below {st:.1f} dB, pass-band ripple {rp:.3f} dB to 9.5 kHz.\n"
                " * out[2n] = x[n - UPS_K], out[2n+1] = sum_k UPS_H[k] (x[n - UPS_K - k] + x[n - UPS_K + 1 + k]). */\n")
        f.write("#pragma once\n\n")
        f.write(f"#define UPS_K {len(odd)}\n")
        f.write("static const float UPS_H[UPS_K] = {" + ", ".join(f"{x:.9e}f" for x in odd) + "};\n")
        # the low-pass before it, at the strings' rate: the impulsive bridge contact leaves energy near the half rate's
        # Nyquist (11 kHz) that the reference does not have (it holds -43 dB above 10 kHz): Butterworth, 4th order
        sos = signal.butter(4, 8500, fs=FS / 2, output="sos")
        f.write("\n/* low-pass at the strings' rate before the interpolator: Butterworth 4th order, 8.5 kHz, two biquads\n"
                " * {b0, b1, b2, a1, a2} (a0 = 1), transposed direct form II */\n#define UPS_LP_N 2\n")
        f.write("static const float UPS_LP[UPS_LP_N][5] = {\n")
        for sec in sos:
            f.write("    {" + ", ".join(f"{x:.9e}f" for x in (sec[0], sec[1], sec[2], sec[4], sec[5])) + "},\n")
        f.write("};\n")
        # the brightness correction (step 2b, after ElectroNick's listening): the half rate and the truncation leave the
        # 4-6.4 kHz bands 3.6-5.9 dB under the reference (tools/reference/diagnose2b.py); one peaking filter, 5.5 kHz,
        # +6 dB, Q 1.1 (RBJ), at the strings' rate
        fs2 = FS / 2
        A_, w = 10 ** (6.0 / 40), 2 * np.pi * 5500 / fs2
        al = np.sin(w) / (2 * 1.1)
        b = np.array([1 + al * A_, -2 * np.cos(w), 1 - al * A_]); a = np.array([1 + al / A_, -2 * np.cos(w), 1 - al / A_])
        b, a = b / a[0], a / a[0]
        f.write("\n/* brightness correction: peaking filter 5.5 kHz, +6 dB, Q 1.1, {b0, b1, b2, a1, a2} */\n")
        f.write("static const float UPS_EQ[5] = {" + ", ".join(f"{x:.9e}f" for x in (b[0], b[1], b[2], a[1], a[2])) + "};\n")
    print("wrote tanpura/upsample_coefs.h:", n, "taps")

if __name__ == "__main__":
    main()
