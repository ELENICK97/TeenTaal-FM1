#!/usr/bin/env python3
"""Step 6: validate data/taal/*.json (format: data/taal/FORMAT.md) and generate taal/taal_tables.h.
    python3 tools/taal_data/build_taal.py [--check]       (--check: validate only; exit 1 with the reasons)
Bol ids are the positions of the bols in data/tabla/bols.json, the same order tools/tabla_data/build_samples.py gives
tabla/tabla_bols.h; the table carries the names too, and taal_selftest() checks them against the tabla's."""
import glob, json, os, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
MAXPART = 8


def bol_table():
    with open(os.path.join(ROOT, "data", "tabla", "bols.json")) as f:
        names = [b for b in json.load(f) if not b.startswith("_")]
    return names, {b.lower(): i for i, b in enumerate(names)}


def load_all():
    names, ids = bol_table()
    errs, taals = [], []
    files = sorted(glob.glob(os.path.join(ROOT, "data", "taal", "*.json")))
    if not files:
        errs.append("data/taal: no taal files")
    seen = set()
    for p in files:
        fn = os.path.relpath(p, ROOT)
        try:
            with open(p) as f:
                t = json.load(f)
        except (OSError, ValueError) as e:
            errs.append(f"{fn}: not valid JSON ({e})")
            continue
        e0 = len(errs)
        for k in ("name", "matras", "vibhag", "marks", "theka"):
            if k not in t:
                errs.append(f"{fn}: '{k}' missing")
        unknown = set(t) - {"name", "matras", "vibhag", "marks", "theka", "tempo", "source"}
        if unknown:
            errs.append(f"{fn}: unknown fields {sorted(unknown)} (FORMAT.md)")
        if len(errs) > e0:
            continue
        name, m, vib, marks, theka = t["name"], t["matras"], t["vibhag"], t["marks"], t["theka"]
        if not isinstance(name, str) or not 1 <= len(name) <= 15 or not name.isascii():
            errs.append(f"{fn}: name: 1..15 ASCII characters")
        if name.lower() in seen:
            errs.append(f"{fn}: name '{name}' already used")
        seen.add(str(name).lower())
        if not isinstance(m, int) or not 3 <= m <= 32:
            errs.append(f"{fn}: matras: 3..32")
            continue
        if not vib or not all(isinstance(v, int) and v > 0 for v in vib) or sum(vib) != m or len(vib) > 8:
            errs.append(f"{fn}: vibhag {vib}: positive, at most 8, adding up to {m} matras")
        if len(marks) != len(vib) or not all(isinstance(k, str) and len(k) == 1 and k in "X0123456789" for k in marks):
            errs.append(f"{fn}: marks: one per vibhag, each X, 0 or 1..9")
        elif "X" in marks[1:]:
            errs.append(f"{fn}: marks: X (sam) only on the first vibhag")
        if not 20 <= t.get("tempo", 120) <= 600:
            errs.append(f"{fn}: tempo: 20..600 matras a minute")
        if len(theka) != m:
            errs.append(f"{fn}: theka has {len(theka)} entries, matras is {m}")
            continue
        steps = []
        for i, e in enumerate(theka):
            parts = e.split("-") if isinstance(e, str) else [""]
            if not 1 <= len(parts) <= MAXPART or any(not p for p in parts):
                errs.append(f"{fn}: matra {i + 1} '{e}': 1..{MAXPART} bols joined by '-'")
                continue
            row = []
            for p in parts:
                if p == "S":
                    row.append(None)
                elif p.lower() in ids:
                    row.append(ids[p.lower()])
                else:
                    errs.append(f"{fn}: matra {i + 1}: unknown bol '{p}' (data/tabla/bols.json has: {', '.join(names)}; "
                                "S is a rest)")
            steps.append(row)
        if len(errs) == e0:
            taals.append(dict(t, steps=steps, file=fn))
    return taals, names, errs


def main():
    taals, names, errs = load_all()
    if errs:
        print("\n".join(errs), file=sys.stderr)
        sys.exit(1)
    if "--check" in sys.argv:
        print(f"data/taal: OK ({len(taals)} taals)")
        return
    used = sorted({b for t in taals for row in t["steps"] for b in row if b is not None})
    matra_rows, step_ids = [], []
    out = os.path.join(ROOT, "taal", "taal_tables.h")
    with open(out, "w") as f:
        f.write("/* taal_tables.h — GENERATED by tools/taal_data/build_taal.py from data/taal/ (JSON): do not edit.\n"
                " * Bol ids: tabla/tabla_bols.h (TAAL_BOLCHECK repeats the names, checked by taal_selftest). */\n"
                "#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define TAAL_N {len(taals)}\n#define TAAL_REST 255\n#define TAAL_MAXPART {MAXPART}\n\n")
        f.write("typedef struct { uint16_t first; uint8_t n, pad; } taal_matra_t;      /* steps first..first+n-1 */\n")
        f.write("typedef struct { const char *name; uint16_t matra0, tempo; uint8_t matras, nvibhag, vibhag[8]; "
                "char mark[8]; } taal_def_t;\n")
        f.write("typedef struct { uint8_t id; const char *name; } taal_bolcheck_t;\n\n")
        for t in taals:
            t["matra0"] = len(matra_rows)
            for row in t["steps"]:
                matra_rows.append((len(step_ids), len(row)))
                step_ids += [255 if b is None else b for b in row]
        f.write(f"static const uint8_t TAAL_STEP[{len(step_ids)}] = {{\n")
        for t in taals:
            f.write(f"    /* {t['name']} */ " + ", ".join(
                ",".join(str(255 if b is None else b) for b in row) for row in t["steps"]) + ",\n")
        f.write("};\n\n")
        f.write(f"static const taal_matra_t TAAL_MATRA[{len(matra_rows)}] = {{\n")
        for t in taals:
            rows = matra_rows[t["matra0"]:t["matra0"] + t["matras"]]
            f.write(f"    /* {t['name']} */ " + " ".join(f"{{{a}, {n}, 0}}," for a, n in rows) + "\n")
        f.write("};\n\n")
        f.write("static const taal_def_t TAAL_DEF[TAAL_N] = {\n")
        for t in taals:
            vib = (t["vibhag"] + [0] * 8)[:8]
            mk = "".join(t["marks"])
            f.write(f"    {{\"{t['name']}\", {t['matra0']}, {t.get('tempo', 120)}, {t['matras']}, {len(t['vibhag'])}, "
                    f"{{{', '.join(map(str, vib))}}}, \"{mk}\"}},   /* {t['file']} */\n")
        f.write("};\n\n")
        f.write(f"static const taal_bolcheck_t TAAL_BOLCHECK[{len(used)}] = {{\n")
        f.write("".join(f"    {{{b}, \"{names[b]}\"}},\n" for b in used))
        f.write("};\n")
    print(f"{len(taals)} taals, {len(matra_rows)} matras, {len(step_ids)} steps, {len(used)} bols used -> {out}")


if __name__ == "__main__":
    main()
